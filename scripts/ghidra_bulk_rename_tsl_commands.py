# Ghidra script: Bulk rename TSL ExecuteCommand handlers using K1 command ID mapping
# Run this in AgentDecompile execute-script on /TSL_GOG_swkotor2
#
# This script:
# 1. Decompiles TSL's InitializeCommands @ 0x0077b530
# 2. Extracts command ID -> handler address mapping
# 3. Cross-references with K1's known command ID -> name mapping
# 4. Renames ~700 unnamed FUN_ functions to their K1 equivalents
#
# Prerequisites: AgentDecompile MCP server must be running with TSL program loaded
from __future__ import annotations

import re

from ghidra.app.decompiler import DecompileOptions, DecompInterface
from ghidra.framework.project import DefaultProject, DefaultProjectManager, ProjectDataService
from ghidra.program.model.listing import FunctionManager, Program
from ghidra.program.model.symbol import SourceType
from ghidra.util.task import ConsoleTaskMonitor

activeProject = DefaultProjectManager().getActiveProject()
projectData = activeProject.getProjectData()
currentProgram = projectData.getCurrentProgram()

fm = currentProgram.getFunctionManager()
af = currentProgram.getAddressFactory()

# Phase 1: Decompile TSL InitializeCommands to get command table
func = fm.getFunctionAt(af.getAddress("0x0077b530"))
if func is None:
    raise Exception("InitializeCommands not found at 0x0077b530")

decomp = DecompInterface()
opts = DecompileOptions()
opts.setMaxPayloadMBytes(256)
decomp.setOptions(opts)
decomp.openProgram(currentProgram)

results = decomp.decompileFunction(func, 600, ConsoleTaskMonitor())
if not results.decompileCompleted():
    decomp.dispose()
    raise Exception("Decompilation failed: %s" % results.getErrorMessage())

code = results.getDecompiledFunction().getC()
decomp.dispose()

# Parse TSL table assignments:
# Pattern: *(code **)(*(int *)(this + 0xc) + OFFSET) = HANDLER;
pattern = re.compile(r"\*\(code \*\*\)\(\*\(int \*\)\(this \+ 0xc\) \+ (0x[0-9a-f]+)\) = (\w+);")
tsl_table = {}  # cmd_id -> handler_name
for offset_str, handler in pattern.findall(code):
    cmd_id = int(offset_str, 16) // 4
    tsl_table[cmd_id] = handler

# Build reverse map: handler_name -> [cmd_ids]
tsl_handler_to_ids = {}
for cmd_id, handler in tsl_table.items():
    if handler not in tsl_handler_to_ids:
        tsl_handler_to_ids[handler] = []
    tsl_handler_to_ids[handler].append(cmd_id)

