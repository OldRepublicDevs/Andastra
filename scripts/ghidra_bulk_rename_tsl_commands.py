# Phase 3: Cross-reference and build renames
renames = {}  # tsl_fun_addr_str -> new_name
skipped_already_named = 0
skipped_no_k1_match = 0

for handler, cmd_ids in tsl_handler_to_ids.items():
    if not handler.startswith("FUN_"):
        skipped_already_named += 1
        continue

    addr_str = handler[4:]  # e.g. "0077f0b0"

    # Find K1 name for any of these cmd_ids
    k1_name = None
    for cid in sorted(cmd_ids):
        if cid in k1:
            candidate = k1[cid]
            if candidate.startswith("return_zero"):
                continue
            k1_name = candidate
            break

    if k1_name is None:
        skipped_no_k1_match += 1
        continue

    renames[addr_str] = k1_name

# Phase 4: Execute renames
program = currentProgram
txn = program.startTransaction("Bulk rename ExecuteCommand handlers from K1 command ID mapping")
renamed_count = 0
rename_errors = []
try:
    for addr_str, new_name in sorted(renames.items()):
        addr = af.getAddress("0x" + addr_str)
        func = fm.getFunctionAt(addr)
        if func is None:
            rename_errors.append("No function at 0x%s" % addr_str)
            continue

        if not func.getName().startswith("FUN_"):
            skipped_already_named += 1
            continue

        try:
            func.setName(new_name, SourceType.USER_DEFINED)
            renamed_count += 1
        except Exception:
            # Name conflict - try with address suffix
            try:
                func.setName("%s_%s" % (new_name, addr_str), SourceType.USER_DEFINED)
                renamed_count += 1
            except Exception as e2:
                rename_errors.append("Failed 0x%s -> %s: %s" % (addr_str, new_name, str(e2)))

    program.endTransaction(txn, True)
except Exception:
    program.endTransaction(txn, False)

# Output summary
output = ["BULK RENAME RESULTS:"]
output.append("  Renamed: %d" % renamed_count)
output.append("  Skipped (already named): %d" % skipped_already_named)
output.append("  Skipped (no K1 match): %d" % skipped_no_k1_match)
output.append("  Errors: %d" % len(rename_errors))
if rename_errors:
    output.append("\nErrors:")
    for err in rename_errors[:20]:
        output.append("  " + err)

__result__ = "\n".join(output)
