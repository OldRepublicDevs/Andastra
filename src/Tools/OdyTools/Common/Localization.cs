        public static void SetLanguage(ToolsetLanguage language)
        {
            _currentLanguage = language;
            _globalTranslator.Language = language;
        }

        public static ToolsetLanguage GetLanguage()
        {
            return _currentLanguage;
        }

        public static string Translate(string key, ToolsetLanguage? language = null, string fallback = null)
        {
            if (string.IsNullOrEmpty(key))
            {
                return "";
            }

            ToolsetLanguage lang = language ?? _currentLanguage;
            if (Translations.TryGetValue(lang, out var langDict) && langDict.TryGetValue(key, out string value))
            {
                return value;
            }

            if (fallback != null && langDict != null && langDict.TryGetValue(fallback, out string fallbackValue))
            {
                return fallbackValue;
            }

            if (lang != ToolsetLanguage.English && Translations.TryGetValue(ToolsetLanguage.English, out var englishDict) && englishDict.TryGetValue(key, out string englishValue))
            {
                return englishValue;
            }

            return key;
        }

        public static string Tr(string text, string fallback = null)
        {
            return Translate(text, null, fallback);
        }

        public static string Trf(string formatString, params object[] args)
        {
            string translated = Translate(formatString);
            try
            {
                return string.Format(translated, args);
            }
            catch
            {
                return translated;
            }
        }

        public static ToolsetLanguage CurrentLanguage
        {
            get => _currentLanguage;
            set => SetLanguage(value);
        }

        public static ToolsetLanguage FromPykotorLanguage(Language language)
        {
            switch (language)
            {
                case Language.English: return ToolsetLanguage.English;
                case Language.French: return ToolsetLanguage.French;
                case Language.German: return ToolsetLanguage.German;
                case Language.Italian: return ToolsetLanguage.Italian;
                case Language.Spanish: return ToolsetLanguage.Spanish;
                case Language.Polish: return ToolsetLanguage.Polish;
                default: return ToolsetLanguage.English;
            }
        }

        /// <summary>
        /// Maps the system's current UI culture to a supported ToolsetLanguage.
        /// Cross-platform: uses CultureInfo.CurrentUICulture (Win7-11, macOS, Linux).
        /// Falls back to English for unsupported locales.
        /// </summary>
        public static ToolsetLanguage GetLanguageFromSystemCulture()
        {
            try
            {
                string code = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
                if (string.IsNullOrEmpty(code)) return ToolsetLanguage.English;
                switch (code.ToLowerInvariant())
                {
                    case "fr": return ToolsetLanguage.French;
                    case "de": return ToolsetLanguage.German;
                    case "it": return ToolsetLanguage.Italian;
                    case "es": return ToolsetLanguage.Spanish;
                    case "pl": return ToolsetLanguage.Polish;
                    default: return ToolsetLanguage.English;
                }
            }
            catch
            {
                return ToolsetLanguage.English;
            }
        }

        /// <summary>
        /// Returns the system language as an int (0-5) for GlobalSettings.SelectedLanguage compatibility.
        /// Used as the default when no user preference is saved.
        /// </summary>
        public static int GetSystemLanguageAsInt()
        {
            return (int)GetLanguageFromSystemCulture();
        }
