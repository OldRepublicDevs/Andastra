    public enum ToolsetLanguage
    {
        English = 0,
        French = 1,
        German = 2,
        Italian = 3,
        Spanish = 4,
        Polish = 5
    }

    public class Translator
    {
        private ToolsetLanguage _language;

        public Translator(ToolsetLanguage language = ToolsetLanguage.English)
        {
            _language = language;
        }

        public ToolsetLanguage Language
        {
            get => _language;
            set => _language = value;
        }

        public string Translate(string text, string fallback = null)
        {
            if (_language == ToolsetLanguage.English)
            {
                return text;
            }

            var translations = Localization.Translations;
            if (translations.TryGetValue(_language, out var langDict) && langDict.TryGetValue(text, out string translated))
            {
                return translated;
            }

            if (fallback != null)
            {
                if (langDict != null && langDict.TryGetValue(fallback, out string fallbackTranslated))
                {
                    return fallbackTranslated;
                }
            }

            return text;
        }

        public string Tr(string text, string fallback = null)
        {
            return Translate(text, fallback);
        }
    }

